FORMS = {}
STEMS = {}   # для A(): основи окремо — тест сам дописує закінчення зі свого еталона
ENDINGS = ADJ[3:-1].split('|')


def W(*forms):
    """Точні словоформи / фрази. Пробіл у фразі = будь-який пробіл, зокрема перенос рядка."""
    alts = '|'.join(f.replace(' ', r'\s+') for f in forms)
    rx = re.compile(f'{WL}(?:{alts}){WR}', re.I)
    FORMS[rx] = list(forms)
    return rx


def A(*stems):
    """Прикметник/дієприкметник: основа + закінчення відмінювання. Не стемінг —
    перелік закінчень одного слова, тому «існуючий» ловиться, «існування» — ні."""
    rx = re.compile(f'{WL}(?:{"|".join(stems)}){ADJ}{WR}', re.I)
    FORMS[rx] = [s + e for s in stems for e in ENDINGS]
    STEMS[rx] = list(stems)
    return rx


