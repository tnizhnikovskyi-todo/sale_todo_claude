# імʼя файлу, а не слово з латиницею
TOKEN = re.compile(rf'(?:[^\W\d_]|[{APOS}])+')
RU_LETTERS = re.compile(r'[ыэъёЫЭЪЁ]')
UNITS = (r'(?:тиж\w*|дн\w*|день|год\w*|міс\w*|рік|роки|років|хв\w*|користувач\w*|люд\w*|'
         r'ос[іо]б\w*|%|€|EUR|грн|тис\w*|млн|етап\w*|сесі\w*|зустріч\w*|модул\w*)')
RANGE_HYPHEN = re.compile(rf'(?<![\w.,/-])\d+(?:[.,]\d+)?-\d+(?:[.,]\d+)?(?![\w.-])(?=\s*{UNITS})')
SPACED_HYPHEN = re.compile(r'(?<=[\w»)])[^\S\n]+(?:-|--)[^\S\n]+(?=[\w«(])')
# «–» з пробілами: між словами має стояти «—»; між двома простими числами — «–» без
# пробілів. Діапазон, член якого сам із пробілом («3 600 – 7 200», «3 тижні – 1,5 місяці»),
# за правописом пишеться з пробілами — його не чіпаємо.
EN_WORDS = re.compile(r'[^\W\d_]+[^\S\n]+–[^\S\n]+[^\W\d_]+')
EN_NUMS = re.compile(r'(?:(?<=[^\d\s])|(?<=[^\d][^\S\n])|^)\d+(?:[.,]\d+)?[^\S\n]+–[^\S\n]+'
                     r'\d+(?:[.,]\d+)?(?![^\S\n]?\d)', re.M)
# зʼєднувач — жирна НАЗВА пункту на початку рядка (або після маркера переліку), далі тире.
# Жирне посеред речення, за яким іде тире («скільки **насправді** — 10 чи 100?»), — це
# наголос, не зʼєднувач: на прикладах дому так спрацьовували 7 із 7
BOLD_DASH = re.compile(r'^[^\S\n]*(?:[-*·•][^\S\n]+|\d+[.)][^\S\n]+)?\*\*[^*\n]+\*\*[^\S\n]*[—–-][^\S\n]', re.M)
# „…“ не чіпаємо: це норма для лапок усередині «…»
STRAIGHT_QUOTES = re.compile(r'"[^"\n]{1,200}"|“[^”“\n]{1,200}”')


def text_of(path):
    """Текст документа. У .docx абзац — це склеєні без пробілу пробіжки `w:t`:
    Word ріже слово на пробіжки посеред («об» + «ʼєкт»), і склейка пробілом
    рвала б слово надвоє — і хибно, і непомітно для перевірок апострофа й букв."""
    if path.endswith('.docx'):
        d = zipfile.ZipFile(path).read('word/document.xml').decode('utf-8')
        paras = []
        for p in re.split(r'</w:p>', d):
            p = re.sub(r'<w:tab/>', '\t', p)
            p = re.sub(r'<w:br/>', '\n', p)
            runs = re.findall(r'<w:t(?:\s[^>]*)?>(.*?)</w:t>|(\t|\n)', p, re.S)
            paras.append(''.join(html.unescape(a) if a else b for a, b in runs))
        return '\n'.join(x for x in paras if x)
    return open(path, encoding='utf-8').read()


def prose(txt):
    """Текст без код-блоків і `коду` — для лапок і тире: у коді лапки законні."""
    txt = re.sub(r'```.*?```', ' ', txt, flags=re.S)
    return re.sub(r'`[^`\n]*`', ' ', txt)


def uniq(xs, limit=6):
    xs = list(dict.fromkeys(x.strip() for x in xs))
    s = ', '.join(f'«{x}»' for x in xs[:limit])
    return s + (f' і ще {len(xs) - limit}' if len(xs) > limit else '')


def findings(path):
    """Список (рівень, клас, повідомлення). Рівень E — блокує, W — попереджає."""
    out = []
    try:
        txt = text_of(path)
    except Exception as e:
        return [(ERR, 'файл', f'не читається: {e}')]

    # директиви розмітки чернетки — не текст документа
    if path.endswith('.md'):
        txt = re.sub(r'\[\[[A-Z]+(?::[^\]]+)?\]\]', ' ', txt)

    def e(cls, msg): out.append((ERR, cls, msg))
    def w(cls, msg): out.append((WARN, cls, msg))

    # ── внутрішнє й чутливе (§3, §4, §13) — як було
    for m in dict.fromkeys(IDS.findall(txt)):
        e('ID', f'ID реєстру в клієнтському тексті: {m} (§3 «прибрати повністю»)')
    for m in dict.fromkeys(TAGS.findall(txt)):
        e('тег', f'тег пріоритету: {m} (§3)')
    if LEVELS.search(txt):
        e('рівень', 'маркер рівня 🔴/🟡 — внутрішній (§3)')
    for m in dict.fromkeys(TRANSCRIPT.findall(txt)):
        e('транскрипт', f'слід транскрипту: {m!r} (§3)')
    labels = [x.strip() for x in SPEAKER_UA.findall(txt)]
    lu = dict.fromkeys(labels)
    if len(lu) >= 2 or any(labels.count(x) >= 2 for x in lu):
        e('репліки', 'мітки реплік транскрипції: ' + ', '.join(f'«{x}»' for x in list(lu)[:3])
          + ' (§3, §12 конвенцій)')
    m = ASKS.search(txt)
    if m:
        e('питання', f'питання до сейла в клієнтському документі: «{m.group(0)}» (§13 конвенцій)')
    for rx, why in MECHANICS + JARGON:
        m = rx.search(txt)
        if m:
            e('механіка' if (rx, why) in MECHANICS else 'жаргон', f'{why} — знайдено «{m.group(0)}»')

    # ── форма письма (§7): помилки
    inv = [INVISIBLE[c] for c in INVISIBLE if c in txt]
    if inv:
        e('невидимі', 'невидимі символи: ' + ', '.join(inv) + ' — видалити')
    tokens = TOKEN.findall(txt)
    mixed = [t for t in tokens if re.search(rf'[{CYR}]', t) and re.search(r'[A-Za-z]', t)]
    if mixed:
        e('букви', f'латиниця всередині кириличного слова: {uniq(mixed)} — набрати кирилицею (§7)')
    ru = [t for t in tokens if RU_LETTERS.search(t) and re.search(rf'[{CYR}]', t)]
    if ru:
        e('букви', f'російські букви ы/э/ъ/ё: {uniq(ru)} (§7 «одна мова на документ»)')
    ap = [m.group(0) for m in re.finditer(rf'[\w]*[{CYR}][\'’‘`′][{CYR}][\w]*', txt)]
    if ap:
        e('апостроф', f'апостроф не ʼ (U+02BC): {uniq(ap)} — стандарт дому один, ʼ (§7)')

    # ── лексика: помилки
    for rx, fix in RUSSISMS:
        hits = [m.group(0) for m in rx.finditer(txt)]
        if hits:
            e('русизм', f'русизм {uniq(hits)} → {fix} (§7)')
    for rx, fix in PARTICIPLES:
        hits = [m.group(0) for m in rx.finditer(txt)]
        if hits:
            e('дієприкметник', f'дієприкметник на -учий/-ючий {uniq(hits)} → {fix} (§7)')
    for rx in BOT_TAILS:
        hits = [m.group(0) for m in rx.finditer(txt)]
        if hits:
            e('бот-хвіст', f'фраза чат-бота {uniq(hits)} — прибрати повністю (§3)')

    # ── попередження
    for rx, fix in CALQUES:
        hits = [m.group(0) for m in rx.finditer(txt)]
        if hits:
            w('калька', f'калька {uniq(hits)} → {fix} (§3, таблиця калік)')
    for rx, fix in CANCELLARY:
        hits = [m.group(0) for m in rx.finditer(txt)]
        if hits:
            w('канцелярит', f'канцелярит {uniq(hits)} → {fix} (§3)')
    for rx in AI_STAMPS:
        hits = [m.group(0) for m in rx.finditer(txt)]
        if hits:
            w('штамп', f'штамп {uniq(hits)} — замінити фактом або прибрати (§3)')

    p = prose(txt)
    if path.endswith('.md'):
        hits = BOLD_DASH.findall(p)
        if hits:
            w('тире', f'тире-зʼєднувач після жирної назви: {len(hits)} раз(и), '
                      f'напр. {uniq(hits, 2)} — переписати реченням або двокрапкою (§7)')
    hits = SPACED_HYPHEN.findall(p)
    if hits:
        w('тире', f'дефіс із пробілами замість тире: {len(hits)} раз(и) — «—» (§7)')
    hits = EN_WORDS.findall(p) + EN_NUMS.findall(p)
    if hits:
        w('тире', f'коротке «–» з пробілами: {uniq(hits, 3)} — між словами «—», '
                  f'у діапазоні «–» без пробілів (§7)')
    hits = STRAIGHT_QUOTES.findall(p)
    if hits:
        w('лапки', f'лапки не «ялинки»: {uniq(hits, 3)} → «…» (§7)')
    hits = RANGE_HYPHEN.findall(txt)
    if hits:
        w('діапазон', f'діапазон через дефіс {uniq(hits)} → «–» без пробілів: «3–4 тижні» (§7)')
    return out


def check(path):
    """Сумісність: лише помилки, рядками."""
    return [msg for lvl, _, msg in findings(path) if lvl == ERR]


def main():
    if len(sys.argv) < 2:
        raise SystemExit('вжиток: check-humizer.py файл.md|файл.docx [...]')
    fail = 0
    for p in sys.argv[1:]:
        fs = findings(p)
        errs = [m for lvl, _, m in fs if lvl == ERR]
        warns = [m for lvl, _, m in fs if lvl == WARN]
        print(f'▸ {p}')
        for b in errs:
            print(f'  ✗ {b}')
        for b in warns:
            print(f'  ⚠ {b}')
        if errs:
            fail = 1
        elif warns:
            print(f'  ок — блокувальних порушень немає; попереджень: {len(warns)} — переглянь')
        else:
            print('  ок — внутрішніх слідів немає')
    sys.exit(fail)


if __name__ == '__main__':
    main()
